const WEEK = ['周日', '周一', '周二', '周三', '周四', '周五', '周六'];

function timeText(): string {
  const d = new Date();
  const p = (n: number): string => String(n).padStart(2, '0');
  return `${d.getFullYear()}年${d.getMonth() + 1}月${d.getDate()}日 ${WEEK[d.getDay()]} ${p(d.getHours())}:${p(d.getMinutes())}`;
}

